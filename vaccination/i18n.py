def get_ui(language_code="ja"):
    """
    指定した言語のUI辞書を返す。

    未登録の言語コードの場合は
    日本語にフォールバックする。
    """

    return UI_TEXT.get(
        language_code,
        UI_TEXT["ja"],
    )


def t(key, language_code="ja"):
    """
    Python側から翻訳文字列を1件取得する。

    指定言語にキーが存在しない場合は
    日本語へフォールバックする。

    日本語にも存在しない場合は
    keyそのものを返す。
    """

    language = UI_TEXT.get(
        language_code,
        UI_TEXT["ja"],
    )

    if key in language:
        return language[key]

    return UI_TEXT["ja"].get(
        key,
        key,
    )