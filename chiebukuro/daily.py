def _pick(seq, key):
    digest = hashlib.sha256(key.encode()).hexdigest()
    return seq[int(digest[:8], 16) % len(seq)]


def today_card(day, person_key=""):
    """その日の「今日のひとこと」。person_key はユーザー ID やブラウザの目印 (占いを人ごとに変える)"""

    number = day.toordinal()
    word = SWISS_GERMAN[number % len(SWISS_GERMAN)]
    trivia = TRIVIA[number % len(TRIVIA)]
    charm = _pick(CHARMS, f"{day.isoformat()}:{person_key}:charm")
    message = _pick(charm[4], f"{day.isoformat()}:{person_key}:message")
    action = _pick(LUCKY_ACTIONS, f"{day.isoformat()}:{person_key}:action")
    return {
        "day": day,
        "word": {"text": word[0], "reading": word[1], "meaning": word[2], "note": word[3]},
        "trivia": trivia,
        "charm": {"emoji": charm[0], "name": charm[1], "german": charm[2], "origin": charm[3], "message": message, "action": action},
    }
