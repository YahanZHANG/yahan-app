# JSON に書き出す
# =========================================================

def build():

    seasoning_names = {
        name
        for name, _de, category, *_rest in INGREDIENTS
        if category == "seasoning"
    }

    ingredients = []

    for name, name_de, category, group, shops, notes, substitutes in INGREDIENTS:

        ingredients.append(
            {
                "name": name,
                "name_de": name_de,
                "category": category,
                "search_group": group,
                "shops": [SHOP_CODES[code] for code in shops],
                "buying_notes": notes,
                "substitutes_for": [
                    {"original_name": original, "tips": tips}
                    for original, tips in substitutes.items()
                ],
            }
        )

    recipes = []

    for item in RECIPES:

        parsed = []

        for text in item["ingredients"]:

            optional = text.startswith("?")
            name, amount = text.lstrip("?").split(":", 1)

            parsed.append(
                {
                    "name": name,
                    "amount": amount,
                    "is_seasoning": name in seasoning_names,
                    "is_optional": optional,
                }
            )

        recipes.append(
            {
                **item,
                "ingredients": parsed,
                "origin": "ai",
                # 2026-10-20 にここまでの料理はすべて承認済み。
                # これから足す料理は "status": "draft" を付けて、確認してから公開する。
                "status": item.get("status", "published"),
            }
        )

    stores = [
        {
            "name": name,
            "kind": kind,
            "city": city,
            "area": area,
            "address": address,
            "website": website,
            "opening_hours": hours,
            "description": description,
            "has_online_shop": online,
        }
        for name, kind, city, area, address, website, hours, description, online in STORES
    ]

    return ingredients, recipes, stores


if __name__ == "__main__":

    ingredients, recipes, stores = build()

    data_dir = Path(__file__).resolve().parent

    for filename, rows in (
        ("ingredients.json", ingredients),
        ("recipes.json", recipes),
        ("stores.json", stores),
    ):
        (data_dir / filename).write_text(
            json.dumps(rows, ensure_ascii=False, indent=1) + "\n",
            encoding="utf-8",
        )

    print(f"食材 {len(ingredients)}件、レシピ {len(recipes)}件、お店 {len(stores)}件")
